from app.models import PostRequest


def build_prompt(request: PostRequest) -> str:
    cafe = request.cafe_name or "الكافيه"
    return f"""
أنت كاتب محتوى وتسويق محلي للكافيهات في الكويت. اكتب بوستاً له شخصية واضحة، لا مجرد جملة عامة عن القهوة.
الفكرة: {request.idea}
الأجواء: {request.mood}
اسم الكافيه: {cafe}
الأسلوب: {request.tone}

ابدأ بخطاف لافت مرتبط بالفكرة، ثم أضف صورة حسية أو سبباً يجعل القارئ يهتم، ثم اختم بدعوة طبيعية. استخدم لهجة كويتية خفيفة ومفهومة، وتجنب الكليشيهات مثل "المزاج غير" و"لحظة تستاهل" إلا إذا كانت موظفة بطريقة جديدة. لا تكرر اسم الكافيه أكثر من مرة، ولا تجعل النص يبدو كإعلان آلي.
أخرج JSON فقط بالمفاتيح التالية:
text: نص من 3 إلى 5 جمل قصيرة، مختلف ومحدد بالفكرة.
call_to_action: دعوة قصيرة ومبتكرة للزيارة أو الطلب، مرتبطة بالفكرة.
hashtags: قائمة من 3 إلى 5 هاشتاقات مرتبطة بالفكرة والمزاج.
لا تخترع أسعاراً أو عروضاً أو معلومات غير مذكورة.
""".strip()